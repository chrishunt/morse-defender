// Get tile index for a character
uint8_t get_font_tile_index(char c) {
    if (c >= 'A' && c <= 'Z') {
        return c - 'A';
    } else if (c >= '0' && c <= '9') {
        return 26 + (c - '0');
    }
    return 0; // Default to 'A' if unknown
}